#!/usr/bin/env node
// Pins the on-device dictation model (#451 slice 5, ADR-0061): one Hugging Face commit, and the
// SHA-256 of every file the app loads from it. The app downloads exactly these files from that
// commit, after consent, and refuses any byte that does not match.
//
//   node scripts/dictation-model-lock.mjs     rewrite src/lib/dictation/modelLock.ts
//
// LFS files carry their SHA-256 in the Hub API; the small JSON files are downloaded once here
// and hashed. Bump REVISION deliberately and review the diff.
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO = 'onnx-community/whisper-base'
const REVISION = '27a07b4b52b3a4c5886134bb4320e93e1a4bbc7c'
const FILES = [
  'config.json',
  'generation_config.json',
  'preprocessor_config.json',
  'tokenizer.json',
  'tokenizer_config.json',
  'onnx/encoder_model_quantized.onnx',
  'onnx/decoder_model_merged_quantized.onnx',
]
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'dictation', 'modelLock.ts')

async function tree(path) {
  const res = await fetch(`https://huggingface.co/api/models/${REPO}/tree/${REVISION}/${path}`)
  if (!res.ok) throw new Error(`tree ${path}: HTTP ${res.status}`)
  return res.json()
}

const listing = [...(await tree('')), ...(await tree('onnx'))]
const entries = []
for (const path of FILES) {
  const meta = listing.find((f) => f.path === path)
  if (!meta) throw new Error(`${path} is not in ${REPO}@${REVISION}`)
  let sha256 = meta.lfs?.oid
  if (!sha256) {
    const res = await fetch(`https://huggingface.co/${REPO}/resolve/${REVISION}/${path}`)
    if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`)
    sha256 = createHash('sha256').update(Buffer.from(await res.arrayBuffer())).digest('hex')
  }
  entries.push({ path, size: meta.size, sha256 })
}

const total = entries.reduce((sum, e) => sum + e.size, 0)
writeFileSync(
  out,
  `// GENERATED by scripts/dictation-model-lock.mjs — do not edit by hand (ADR-0061).
// Whisper "base" (multilingual, Apache-2.0), int8-quantised ONNX export, ${(total / 1e6).toFixed(1)} MB in total.

export const DICTATION_MODEL = {
  repo: '${REPO}',
  revision: '${REVISION}',
  totalBytes: ${total},
  files: ${JSON.stringify(entries, null, 2).replace(/\n/g, '\n  ')},
} as const
`,
)
console.log(`dictation-model-lock: ${entries.length} files, ${(total / 1e6).toFixed(1)} MB, pinned to ${REVISION}`)
