#!/usr/bin/env node
// Prisma generator: writes the schema's data model to src/prisma/schema-model.generated.ts.
//
// Up to Prisma 6 the client carried the full data model at runtime (`Prisma.dmmf`), including each field's `///`
// documentation. Prisma 7 keeps only name, kind and type there. The field encryption reads its `@encrypted`
// annotations from the documentation, and the key rotation and the data export need list/id flags and column names.
// A generator receives the complete model from `prisma generate`, so this file is written in the same step as the
// client and cannot drift from the schema.
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import generatorHelper from '@prisma/generator-helper'

const { generatorHandler } = generatorHelper

/** Pure: the models as `prisma generate` describes them, in the shape `Prisma.dmmf` had up to Prisma 6. */
export function schemaModelOf(datamodel) {
  return { datamodel: { models: datamodel.models } }
}

export function render(model) {
  return [
    '// Generated by prisma/generators/schema-model.mjs during `prisma generate`. Do not edit.',
    "import type { SchemaModel } from './schema-model.js'",
    '',
    `export const SCHEMA_MODEL: SchemaModel = ${JSON.stringify(model, null, 2)}`,
    '',
  ].join('\n')
}

generatorHandler({
  onManifest: () => ({ prettyName: 'Schema model for field encryption', defaultOutput: '../src/prisma' }),
  onGenerate: async (options) => {
    const target = join(options.generator.output?.value ?? join(dirname(options.schemaPath), '../src/prisma'), 'schema-model.generated.ts')
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, render(schemaModelOf(options.dmmf.datamodel)))
  },
})
