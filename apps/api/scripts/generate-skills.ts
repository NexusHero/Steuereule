/**
 * Reads the owl's skills (`apps/api/skills/<id>/SKILL.md` and their references) at build time and
 * writes them, word for word, into a module the API imports. Nothing is loaded at runtime, and no
 * skill text is copied into TypeScript by hand. The output is not tracked: install, build,
 * typecheck and test all run this first. Run: pnpm --filter @steuereule/api run skills:generate
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ADVISOR_SKILL_COMMANDS, ADVISOR_SKILL_IDS } from '@steuereule/core'

const API_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const SKILLS_DIR = join(API_ROOT, 'skills')
export const SKILLS_TARGET = join(API_ROOT, 'src/ki/skills.generated.ts')

export interface SkillFile {
  readonly name: string
  readonly description: string
  readonly activation: 'always' | 'user'
  readonly command?: string
  readonly references: readonly string[]
  readonly body: string
}

/** The frontmatter is flat `key: value` lines; a value in brackets is a list. */
export function parseSkill(source: string, folder: string): SkillFile {
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(source.replace(/\r\n/g, '\n'))
  if (!match) throw new Error(`skills/${folder}/SKILL.md: frontmatter between --- lines is missing`)
  const fields = new Map<string, string>()
  for (const line of match[1]!.split('\n')) {
    const field = /^([a-z]+):\s*(.*)$/.exec(line.trim())
    if (!field) throw new Error(`skills/${folder}/SKILL.md: cannot read frontmatter line "${line}"`)
    fields.set(field[1]!, field[2]!.trim())
  }
  const list = (value: string | undefined) => (value ? value.replace(/^\[|\]$/g, '').split(',').map((item) => item.trim()).filter(Boolean) : [])
  const name = fields.get('name') ?? ''
  const activation = fields.get('activation')
  const command = fields.get('command')
  if (name !== folder) throw new Error(`skills/${folder}/SKILL.md: name "${name}" must equal the folder name`)
  if (activation !== 'always' && activation !== 'user') throw new Error(`skills/${folder}/SKILL.md: activation must be "always" or "user"`)
  if (!fields.get('description')) throw new Error(`skills/${folder}/SKILL.md: description is missing`)
  if (command && activation !== 'user') throw new Error(`skills/${folder}/SKILL.md: only a skill the user switches on has a command`)
  const body = match[2]!.trim()
  if (body.length === 0) throw new Error(`skills/${folder}/SKILL.md: the instructions are empty`)
  return { name, description: fields.get('description')!, activation, ...(command ? { command } : {}), references: list(fields.get('references')), body }
}

function readSkills(dir: string): SkillFile[] {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .map((folder) => parseSkill(readFileSync(join(dir, folder, 'SKILL.md'), 'utf8'), folder))
}

/** The skills the user switches on must be exactly the ones the app knows, with the same commands. */
function checkAgainstCore(skills: readonly SkillFile[]): void {
  const userSkills = skills.filter((skill) => skill.activation === 'user')
  const ids = userSkills.map((skill) => skill.name).sort()
  const known = [...ADVISOR_SKILL_IDS].sort()
  if (JSON.stringify(ids) !== JSON.stringify(known)) throw new Error(`skills: folders ${JSON.stringify(ids)} do not match ADVISOR_SKILL_IDS ${JSON.stringify(known)}`)
  for (const skill of userSkills) {
    const commands = Object.entries(ADVISOR_SKILL_COMMANDS).filter(([, id]) => id === skill.name).map(([command]) => command)
    if (JSON.stringify(commands) !== JSON.stringify(skill.command ? [skill.command] : [])) throw new Error(`skills/${skill.name}: command "${skill.command ?? ''}" does not match ADVISOR_SKILL_COMMANDS`)
  }
  if (skills.filter((skill) => skill.activation === 'always').length !== 1) throw new Error('skills: exactly one skill must be "always" (the advisor stance)')
}

export function renderSkillsModule(dir: string = SKILLS_DIR): string {
  const skills = readSkills(dir)
  checkAgainstCore(skills)
  const stance = skills.find((skill) => skill.activation === 'always')!
  const knowledge = stance.references.map((topic) => {
    const path = join(dir, stance.name, 'references', `${topic}.md`)
    if (!existsSync(path)) throw new Error(`skills/${stance.name}: reference "${topic}" has no file references/${topic}.md`)
    const text = readFileSync(path, 'utf8').trim()
    const title = /^#\s+(.+)$/m.exec(text)?.[1]?.trim() ?? topic
    return `  ${JSON.stringify(topic)}: { title: ${JSON.stringify(title)}, text: ${JSON.stringify(text)} },`
  })
  const userSkills = skills.filter((skill) => skill.activation === 'user')
  return [
    '// GENERATED by apps/api/scripts/generate-skills.ts from apps/api/skills. Do not edit, do not commit.',
    `/** The advisor stance: the instructions of the \`${stance.name}\` skill, in every prompt. */`,
    `export const ADVISOR_STANCE_TEXT = ${JSON.stringify(stance.body)}`,
    '',
    '/** What the model is told while a skill the user switched on is active. */',
    'export const ADVISOR_SKILL_TEXTS = {',
    ...userSkills.map((skill) => `  ${JSON.stringify(skill.name)}: ${JSON.stringify(skill.body)},`),
    '} as const',
    '',
    `export const ADVISOR_KNOWLEDGE_TOPICS = ${JSON.stringify(stance.references)} as const`,
    'export type AdvisorKnowledgeTopic = (typeof ADVISOR_KNOWLEDGE_TOPICS)[number]',
    '',
    'export const ADVISOR_KNOWLEDGE: Readonly<Record<AdvisorKnowledgeTopic, { readonly title: string; readonly text: string }>> = {',
    ...knowledge,
    '}',
    '',
  ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(SKILLS_TARGET, renderSkillsModule())
}
