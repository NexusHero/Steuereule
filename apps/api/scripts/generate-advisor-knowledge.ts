/**
 * Turns the reference files of the `steuerberater` skill into a module the API can ship (#499).
 * The skill stays the one place the knowledge is written; `advisor-knowledge.test.ts` fails when
 * this module is out of date. Run: pnpm --filter @steuereule/api run knowledge:generate
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../../..')
export const KNOWLEDGE_SOURCE_DIR = join(ROOT, '.agents/skills/steuerberater/references')
export const KNOWLEDGE_TARGET = join(ROOT, 'apps/api/src/ki/advisor-knowledge.generated.ts')

/** Topic id → file. `quellen.md` tells an agent how to look things up on the web; the owl cannot. */
export const KNOWLEDGE_TOPICS = [
  'kennzahlen',
  'gestaltung',
  'arbeitnehmer',
  'familie-sonderausgaben',
  'kapital-vermietung-rente',
  'selbststaendige-ust',
  'grenzgaenger-ausland',
  'erbschaft-schenkung',
  'verfahren',
] as const

export function renderKnowledgeModule(read: (topic: string) => string = (topic) => readFileSync(join(KNOWLEDGE_SOURCE_DIR, `${topic}.md`), 'utf8')): string {
  const entries = KNOWLEDGE_TOPICS.map((topic) => {
    const text = read(topic).trim()
    const title = /^#\s+(.+)$/m.exec(text)?.[1]?.trim() ?? topic
    return `  ${JSON.stringify(topic)}: { title: ${JSON.stringify(title)}, text: ${JSON.stringify(text)} },`
  })
  return [
    '// GENERATED by apps/api/scripts/generate-advisor-knowledge.ts from .agents/skills/steuerberater/references. Do not edit.',
    `export const ADVISOR_KNOWLEDGE_TOPICS = ${JSON.stringify(KNOWLEDGE_TOPICS)} as const`,
    'export type AdvisorKnowledgeTopic = (typeof ADVISOR_KNOWLEDGE_TOPICS)[number]',
    '',
    'export const ADVISOR_KNOWLEDGE: Readonly<Record<AdvisorKnowledgeTopic, { readonly title: string; readonly text: string }>> = {',
    ...entries,
    '}',
    '',
  ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(KNOWLEDGE_TARGET, renderKnowledgeModule())
  console.log(`Wrote ${KNOWLEDGE_TARGET}`)
}
