// node --test scripts/checks/pr-body-footer-check.test.mjs
import assert from 'node:assert/strict'
import { test } from 'node:test'
import { findFooter } from './pr-body-footer-check.mjs'

test('the ADR-0017 footer literal is found', () => {
  assert.equal(findFooter('Summary\n\n_Generated by [Claude Code](https://claude.ai/code)_'), '_Generated by [Claude Code](https://claude.ai/code)_')
})

test('the "Generated with" variant is found, case-insensitively and with CRLF line ends', () => {
  assert.match(findFooter('Body\r\n\r\n🤖 generated WITH [Claude Code](https://claude.com/claude-code)'), /Claude Code/)
})

test('a clean body, including the persona trailer, passes', () => {
  assert.equal(findFooter('## Evidence\nAll gates green.\n\nCo-authored-by: Salih <salih@steuereule-crew.example>'), null)
})

test('an empty or missing body passes', () => {
  assert.equal(findFooter(''), null)
  assert.equal(findFooter(undefined), null)
})

test('prose that merely mentions Claude Code does not trip it', () => {
  assert.equal(findFooter('The Claude Code footer is stripped by hand, see ADR-0017.'), null)
})
