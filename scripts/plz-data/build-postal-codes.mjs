#!/usr/bin/env node
// Builds the PLZ → [{ Ort, Bundesland }] table shipped in @steuereule/core (#451 slice 3, decision 8).
//
// Source: the OpenStreetMap street extract published by the OpenPLZ API project
// (github.com/openpotato/openplzapi.data, file src/de/osm/streets.updated.csv, ODbL 1.0). Each row
// is one OSM street with the postal-code area, the municipality and its 8-digit Regionalschlüssel
// it falls in; the first two digits of that key are the Bundesland. Aggregating the rows per postal
// code yields every Ort a PLZ touches — which is exactly the "several places → choose" case the UI
// needs (e.g. 21039 spans Hamburg and three Schleswig-Holstein municipalities).
//
// Run yearly and commit the result:
//   node scripts/plz-data/build-postal-codes.mjs            # downloads the pinned commit
//   node scripts/plz-data/build-postal-codes.mjs --source ./streets.updated.csv
// Bump SOURCE_COMMIT to the newest commit of openpotato/openplzapi.data when refreshing.
//
// The app never fetches this data at runtime: the table is bundled, the lookup stays on the device.
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE_REPO = 'openpotato/openplzapi.data'
const SOURCE_COMMIT = 'c26389b30573ab2738d0b14fd350f143aa0a1251'
const SOURCE_FILE = 'src/de/osm/streets.updated.csv'
const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../packages/core/src/common/postal-codes.data.ts')

/** First two digits of the Regionalschlüssel → state code used by `GERMAN_STATES`. */
const STATE_BY_KEY = {
  '01': 'SH', '02': 'HH', '03': 'NI', '04': 'HB', '05': 'NW', '06': 'HE', '07': 'RP', '08': 'BW',
  '09': 'BY', '10': 'SL', '11': 'BE', '12': 'BB', '13': 'MV', '14': 'SN', '15': 'ST', '16': 'TH',
}

function parseCsvLine(line) {
  const out = []
  let cur = ''
  let quoted = false
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i]
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') {
        cur += '"'
        i += 1
      } else if (ch === '"') quoted = false
      else cur += ch
    } else if (ch === '"') quoted = true
    else if (ch === ',') {
      out.push(cur)
      cur = ''
    } else cur += ch
  }
  out.push(cur)
  return out
}

async function loadSource() {
  const i = process.argv.indexOf('--source')
  if (i !== -1) return readFile(process.argv[i + 1], 'utf8')
  const url = `https://raw.githubusercontent.com/${SOURCE_REPO}/${SOURCE_COMMIT}/${SOURCE_FILE}`
  console.log(`[plz-data] downloading ${url}`)
  const res = await fetch(url)
  if (!res.ok) throw new Error(`download failed: HTTP ${res.status}`)
  return res.text()
}

function fail(message) {
  console.error(`[plz-data] FAIL — ${message}`)
  process.exit(1)
}

const text = await loadSource()
const lines = text.split(/\r?\n/)
const header = parseCsvLine(lines[0])
const col = (name) => {
  const idx = header.indexOf(name)
  if (idx === -1) fail(`column ${name} missing in ${header.join(',')}`)
  return idx
}
const [iPlz, iOrt, iKey] = [col('PostalCode'), col('Locality'), col('RegionalKey')]

/** plz → Map("ort~state" → number of streets) */
const byPlz = new Map()
for (const line of lines.slice(1)) {
  if (!line) continue
  const row = parseCsvLine(line)
  const plz = row[iPlz]
  const ort = row[iOrt]?.trim()
  const state = STATE_BY_KEY[row[iKey]?.slice(0, 2)]
  if (!plz || !ort || !state) continue
  if (/[~|=\n]/.test(ort)) fail(`place name ${JSON.stringify(ort)} contains a separator`)
  const places = byPlz.get(plz) ?? new Map()
  const key = `${ort}~${state}`
  places.set(key, (places.get(key) ?? 0) + 1)
  byPlz.set(plz, places)
}

const entries = [...byPlz.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([plz, places]) => {
    const ranked = [...places.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0], 'de'))
    // A single stray street (centroid just across a border) is noise, unless it is all we have.
    const kept = ranked.filter(([, streets], index) => index === 0 || streets > 1)
    return `${plz}=${kept.map(([key]) => key).join('|')}`
  })

// Plausibility (ticket: ~8.200 PLZ, each exactly five digits, every Bundesland present).
if (entries.length < 8000 || entries.length > 8400) fail(`expected about 8.200 postal codes, got ${entries.length}`)
const bad = entries.filter((e) => !/^\d{5}=/.test(e))
if (bad.length > 0) fail(`postal codes that are not five digits: ${bad.slice(0, 5).join(', ')}`)
const states = new Set(entries.flatMap((e) => e.split('=')[1].split('|').map((p) => p.split('~')[1])))
const missing = Object.values(STATE_BY_KEY).filter((s) => !states.has(s))
if (missing.length > 0) fail(`states without a postal code: ${missing.join(', ')}`)

const retrieved = new Date().toISOString().slice(0, 10)
const body = `// GENERATED by scripts/plz-data/build-postal-codes.mjs — do not edit by hand.
//
// Source: OpenStreetMap street extract by the OpenPLZ API project,
// https://github.com/${SOURCE_REPO}/blob/${SOURCE_COMMIT}/${SOURCE_FILE}
// Retrieved: ${retrieved}. Postal codes: ${entries.length}.
// License: © OpenStreetMap contributors, Open Database License (ODbL) 1.0,
// https://opendatacommons.org/licenses/odbl/1-0/ — attribution is shown under Rechtliches.
//
// Format: one line per postal code, \`PLZ=Ort~Land|Ort~Land\`, places ordered by how many streets
// of the postal code lie in them (the most likely Ort first).

export const POSTAL_CODE_SOURCE = {
  name: 'OpenStreetMap (OpenPLZ API extract)',
  url: 'https://github.com/${SOURCE_REPO}',
  commit: '${SOURCE_COMMIT}',
  retrieved: '${retrieved}',
  license: 'ODbL-1.0',
} as const

export const POSTAL_CODE_TABLE = ${JSON.stringify(entries.join('\n'))}
`
await writeFile(OUT, body)
console.log(`[plz-data] wrote ${entries.length} postal codes (${(body.length / 1024).toFixed(0)} KB) to ${path.relative(process.cwd(), OUT)}`)
