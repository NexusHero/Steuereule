#!/usr/bin/env node
// Builds the BLZ → Bankname table shipped in @steuereule/core (#452 slice 5, decision 12): the
// master-data IBAN field names the bank offline, no request leaves the device.
//
// Source: the Bankleitzahlendatei of the Deutsche Bundesbank (TXT, fixed width, ISO-8859-1),
// https://www.bundesbank.de/de/startseite/bankleitzahlendateien-txt--602678 . It changes quarterly
// (the Monday after the first Saturday of March, June, September, December); run this script with
// the new file each time and commit the result:
//   node scripts/blz-data/build-bank-codes.mjs --source BLZ.TXT --valid "07.09.2026–06.12.2026"
//
// Record layout (Bundesbank "Bankleitzahlendatei – Satzaufbau"): 1–8 BLZ, 9 Merkmal (1 = the
// payment service provider itself, 2 = a branch that keeps the BLZ), 10–67 Bezeichnung.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../packages/core/src/common/bank-codes.data.ts')
const arg = (name) => {
  const i = process.argv.indexOf(name)
  return i === -1 ? null : process.argv[i + 1]
}
const source = arg('--source')
const valid = arg('--valid')
if (!source || !valid) {
  console.error('usage: node scripts/blz-data/build-bank-codes.mjs --source BLZ.TXT --valid "<gültig von–bis>"')
  process.exit(1)
}

const text = new TextDecoder('latin1').decode(readFileSync(source))
const banks = new Map()
for (const line of text.split(/\r?\n/)) {
  if (line.length < 67 || line[8] !== '1') continue
  const blz = line.slice(0, 8)
  const name = line.slice(9, 67).trim()
  if (!/^\d{8}$/.test(blz) || !name || /[=|\n]/.test(name)) continue
  if (!banks.has(blz)) banks.set(blz, name)
}
if (banks.size < 3000 || banks.size > 5000) {
  console.error(`[blz-data] FAIL — expected about 3.500 banks, got ${banks.size}`)
  process.exit(1)
}
const entries = [...banks.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([blz, name]) => `${blz}=${name}`)
const retrieved = new Date().toISOString().slice(0, 10)
writeFileSync(
  OUT,
  `// GENERATED by scripts/blz-data/build-bank-codes.mjs — do not edit by hand.
//
// Source: Deutsche Bundesbank, Bankleitzahlendatei (TXT), gültig ${valid}, retrieved ${retrieved}.
// https://www.bundesbank.de/de/startseite/bankleitzahlendateien-txt--602678
// One line per Bankleitzahl of a payment service provider (Merkmal 1): \`BLZ=Bezeichnung\`.

export const BANK_CODE_SOURCE = { name: 'Deutsche Bundesbank, Bankleitzahlendatei', valid: '${valid}', retrieved: '${retrieved}' } as const

export const BANK_CODE_TABLE = ${JSON.stringify(entries.join('\n'))}
`,
)
console.log(`[blz-data] wrote ${entries.length} banks to ${path.relative(process.cwd(), OUT)}`)
