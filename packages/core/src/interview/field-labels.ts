/** The field's name as the user reads it, or null when the app has none for it. */
export function fieldLabel(screen: Screen | string, field: string): string | null {
  return LABELS[screen as Screen]?.[field] ?? null
}

/** A field's label by its id alone, when one screen's field has it (for text that names no mask). */
export function fieldLabelOfId(field: string): string | null {
  for (const labels of Object.values(LABELS)) {
    const label = labels?.[field]
    if (label !== undefined) return label
  }
  return null
}
